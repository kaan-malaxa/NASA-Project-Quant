"""Read project configuration without modifying science decisions."""
from dataclasses import dataclass, field
from itertools import pairwise
from pathlib import Path

import yaml

from pipeline.common import paths


@dataclass(frozen=True)
class Region:
    id: str
    name: str
    country: str
    bbox: list[float]
    polygon: str | None
    fire_type: str
    story: str
    synthetic: bool
    firms_country_names: list[str] = field(default_factory=list)
    # "local_us": the tracked United_States CSVs under data/; "firms_world": one FIRMS country from
    # the lossless all-country store under data/FIRMS_world/ (see pipeline.ingest.world_data).
    source: str = "local_us"


SOURCES = ("local_us", "firms_world")


def _yaml(path):
    loader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
    with path.open(encoding="utf-8") as handle:
        return yaml.load(handle, Loader=loader)


def load_core_regions() -> list[Region]:
    """regions.yaml: the United States region plus any simulated (planted-truth) regions."""
    regions = [Region(**row) for row in _yaml(paths.config_file("regions.yaml"))["regions"]]
    real = [region for region in regions if not region.synthetic]
    if len(real) != 1:
        raise ValueError("Configure exactly one real-data region in regions.yaml: us")
    require_us_region(real[0])
    return regions


_WORLD_CACHE: dict = {}


def load_world_regions() -> list[Region]:
    """world_regions.yaml: one region per FIRMS country (generated by pipeline.ingest.world_regions).

    Parsed and validated once per file version (path, size, modification time, project root)."""
    path = paths.world_regions_config()
    if not path.is_file():
        return []
    stat = path.stat()
    key = (str(path), stat.st_size, stat.st_mtime_ns, str(paths.PROJECT_ROOT), str(paths.source_data_root()))
    if _WORLD_CACHE.get("key") != key:
        regions = [Region(**row) for row in (_yaml(path) or {}).get("regions") or []]
        for region in regions:
            require_world_region(region)
        _WORLD_CACHE.update(key=key, regions=regions)
    return list(_WORLD_CACHE["regions"])


def load_regions() -> list[Region]:
    """Core regions first (us, then simulated ones), then every configured FIRMS world country."""
    regions = [*load_core_regions(), *load_world_regions()]
    if len({region.id for region in regions}) != len(regions):
        raise ValueError("Region ids must be unique")
    return regions


def real_region() -> Region:
    """The default real-data region, us (contracts section 4.1)."""
    return next(region for region in load_core_regions() if not region.synthetic)


def require_us_region(region) -> None:
    """The us region may only use the local United_States country CSVs."""
    if (
        region.id != "us" or region.country != "US" or region.synthetic
        or region.firms_country_names != ["United_States"] or region.source != "local_us"
    ):
        raise ValueError("Only the us region using local United_States CSVs is enabled")


def require_world_region(region) -> None:
    """A world region reads exactly one FIRMS country from the lossless world store."""
    if (
        region.source != "firms_world" or region.synthetic or region.id in ("us", "synthland")
        or len(region.firms_country_names) != 1 or not region.polygon
        or region.polygon != paths.world_polygon(region.id).relative_to(paths.PROJECT_ROOT).as_posix()
    ):
        raise ValueError(f"Invalid FIRMS world region: {region.id}")
    paths.world_file("modis", 2000, region.firms_country_names[0])  # validates the country token


def require_real_region(region) -> None:
    """Real hotspot data: the local US CSVs, or one country from the FIRMS world store."""
    if region.source == "firms_world":
        require_world_region(region)
    else:
        require_us_region(region)


def get_region(region_id) -> Region:
    for region in load_regions():
        if region.id == region_id:
            return region
    raise ValueError(f"Unknown region: {region_id}")


def load_science() -> dict:
    path = paths.config_file("science.yaml")
    if not path.is_file():
        raise FileNotFoundError(
            f"Missing science configuration: {path}. R3 must supply pipeline/config/science.yaml."
        )
    with path.open(encoding="utf-8") as handle:
        result = yaml.safe_load(handle)
    if not isinstance(result, dict):
        raise TypeError(f"Science configuration must be a mapping: {path}")
    return result


def region_centroid(region) -> tuple[float, float]:
    """Return polygon area centroid, or download-box centre if polygon is absent."""
    import json

    if isinstance(region, str):
        region = get_region(region)
    path = paths.PROJECT_ROOT / region.polygon if region.polygon else None
    if path and path.is_file():
        with Path(path).open(encoding="utf-8") as handle:
            geo = json.load(handle)
        if geo["type"] == "FeatureCollection":
            geometries = [feature["geometry"] for feature in geo["features"]]
        elif geo["type"] == "Feature":
            geometries = [geo["geometry"]]
        else:
            geometries = [geo]
        area = cx = cy = 0.0
        for geometry in geometries:
            if geometry["type"] not in {"Polygon", "MultiPolygon"}:
                raise ValueError("Region geometry must be Polygon or MultiPolygon")
            polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
            for polygon in polygons:
                for index, ring in enumerate(polygon):
                    cross = [(a[0] * b[1] - b[0] * a[1]) for a, b in pairwise(ring)]
                    signed = sum(cross) / 2
                    if signed == 0:
                        continue
                    weight = abs(signed) * (1 if index == 0 else -1)
                    cx += weight * sum((a[0] + b[0]) * c for a, b, c in zip(ring, ring[1:], cross)) / (6 * signed)
                    cy += weight * sum((a[1] + b[1]) * c for a, b, c in zip(ring, ring[1:], cross)) / (6 * signed)
                    area += weight
        if area <= 0:
            raise ValueError("Region polygon has no positive area")
        return cx / area, cy / area
    west, south, east, north = region.bbox
    return (west + east) / 2, (south + north) / 2

import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const directory = new URL("../../contracts/", import.meta.url);
const names = (await readdir(directory)).filter((name) => name.endsWith(".schema.json")).sort();
const schemas = Object.fromEntries(await Promise.all(names.map(async (name) => [name, JSON.parse(await readFile(new URL(name, directory), "utf8"))])));
const camel = (name) => name.replace(/\.schema\.json$/, "").split(/[_-]/).map((part) => part[0].toUpperCase() + part.slice(1)).join("");
const referenceName = (ref, current) => {
  const [file, fragment] = ref.split("#");
  const name = file || current;
  return fragment ? camel(name) + camel(fragment.split("/").at(-1)) : camel(name) + "Json";
};
function type(schema, file) {
  if (schema === false) return "never";
  if (schema === true) return "unknown";
  if (schema.$ref) return referenceName(schema.$ref, file);
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.anyOf || schema.oneOf) return (schema.anyOf || schema.oneOf).map((item) => `(${type(item, file)})`).join(" | ");
  if (schema.allOf) return schema.allOf.map((item) => `(${type(item, file)})`).join(" & ");
  if (Array.isArray(schema.type)) return schema.type.map((value) => type({ ...schema, type: value }, file)).join(" | ");
  if (schema.type === "null") return "null";
  if (schema.type === "number" || schema.type === "integer") return "number";
  if (schema.type === "boolean" || schema.type === "string") return schema.type;
  if (schema.type === "array") {
    if (schema.prefixItems) return `[${schema.prefixItems.map((item) => type(item, file)).join(", ")}]`;
    if (schema.minItems === schema.maxItems && schema.minItems > 0) return `[${Array.from({length: schema.minItems}, () => type(schema.items || {}, file)).join(", ")}]`;
    return `Array<${type(schema.items || {}, file)}>`;
  }
  if (schema.type === "object" || schema.properties) {
    const properties = Object.entries(schema.properties || {}).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${type(value, file)}`);
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") properties.push(`[key: string]: ${type(schema.additionalProperties, file)}`);
    return `{ ${properties.join("; ")} }`;
  }
  return "unknown";
}
let output = "// Generated by npm run gen:types from contracts/*.schema.json. Do not edit.\n";
for (const [file, schema] of Object.entries(schemas)) {
  for (const [name, definition] of Object.entries(schema.$defs || {})) output += `export type ${camel(file)}${camel(name)} = ${type(definition, file)};\n`;
  output += `export type ${camel(file)}Json = ${type(schema, file)};\n`;
}
output += 'export type SeriesId = CommonWebSeries | "naive_splice";\nexport type DateRange = { from: string; to: string };\nexport type CellRef = { year: number; week?: number; month?: number };\n';
const destination = new URL("../src/data/types.gen.d.ts", import.meta.url);
await writeFile(destination, output);
console.log(`Generated ${names.length} contracts in ${fileURLToPath(destination)}`);
